REGION_ALIASES = {
    "кузбасс": "кемеровская область",
    "татарстан": "республика татарстан",
}


def get_region_cities(region: str) -> list[str]:
    key = region.lower().strip()
    key = REGION_ALIASES.get(key, key)
    if key in REGION_CITIES:
        return REGION_CITIES[key]
    matches = [(name, cities) for name, cities in REGION_CITIES.items() if name in key or key in name]
    return max(matches, key=lambda item: len(item[0]))[1] if matches else []
