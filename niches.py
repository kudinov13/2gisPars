def expand_rubrics(values: list[str], use_synonyms: bool = True) -> list[str]:
    result = []
    seen = set()
    for value in values:
        value = value.strip()
        if not value:
            continue
        key = NICHE_ALIASES.get(value.lower(), value.lower())
        variants = NICHE_SYNONYMS.get(key, [value]) if use_synonyms else [value]
        for variant in variants:
            normalized = variant.lower()
            if normalized not in seen:
                seen.add(normalized)
                result.append(variant)
    return result
